// First reactions to an authored choice, with darker branches kept visibly hurt.
const choiceMoods={
 'first-day-choice':['happy','neutral','sad'],
 'seat':['shy','shy','shy'],
 'lunch-choice':['shy','happy','sad'],
 'personal-choice':['shy','happy','sad'],
 'personal-promise':['shy','happy','sad'],
 'conflict-public':['neutral','sad','sad'],
 'repair-choice':['shy','neutral','sad'],
 'rain-care':['happy','shy','sad'],
 'festival-choice':['happy','happy','sad'],
 'festival-hand':['love','shy','sad'],
 'roof-repair':['shy','neutral','sad'],
 'roof-intent':['love','shy','sad']
};
function applyLine(moods,line){
 const cue=spoken.get(`${line.speaker}\n${line.text}`);
 if(cue)moods[line.speaker]=cue;
 Object.assign(moods,reactions.get(line.text)||{});
 if(HEROES[line.speaker]&&HEROES[line.speaker].files[line.emotion])moods[line.speaker]=line.emotion;
 for(const [id,emotion] of Object.entries(line.expressions||{}))if(HEROES[id]?.files[emotion])moods[id]=emotion;
}
export function storyExpressions(state){
 const moods=Object.fromEntries(Object.keys(HEROES).map(id=>[id,'neutral']));
 if(!['story','choice'].includes(state.phase)||!Array.isArray(state.script))return moods;
 if(state.nodeId==='repair-result')for(const id of Object.keys(moods))moods[id]='happy';
 if(state.nodeId==='crisis'||state.nodeId==='roof-farewell')for(const id of Object.keys(moods))moods[id]='sad';
 if(state.nodeId==='conflict-private'&&HEROES[state.routeHero||state.episodeHero])moods[state.routeHero||state.episodeHero]='sad';
 const branch=state.nodeId?.match(/^(.*)~([012])$/),reaction=branch&&choiceMoods[branch[1]]?.[Number(branch[2])];
 const target=state.routeHero||state.episodeHero;
 if(reaction){
  if(HEROES[target])moods[target]=reaction;
  else for(const line of state.script)if(HEROES[line.speaker])moods[line.speaker]=reaction;
 }
 for(const line of state.script.slice(0,state.line+1))applyLine(moods,line);
 return moods;
}
